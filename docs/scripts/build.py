#!/usr/bin/env python3
"""Validate bilingual guide content and bundle it for offline browser use."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBRARIES = ['model-change-set', 'relational-paths', 'pg-task-lease', 'reactive-pipeline-kit']

def translation(value, label):
    assert isinstance(value, dict), f'{label}: expected bilingual object'
    for lang in ('en', 'ru'):
        assert isinstance(value.get(lang), str) and value[lang].strip(), f'{label}: missing {lang}'

def main():
    guides = []
    for library_id in LIBRARIES:
        path = ROOT / 'content' / f'{library_id}.json'
        guide = json.loads(path.read_text())
        assert guide['id'] == library_id
        assert guide['repo'] == f'https://github.com/59Alex/{library_id}'
        assert guide['version'] == '0.3.0'
        translation(guide['summary'], f'{library_id}/summary')
        ids = set()
        assert guide['sections'], f'{library_id}: no sections'
        for section in guide['sections']:
            label = f"{library_id}/{section['id']}"
            assert re.fullmatch(r'[a-z0-9-]+', section['id']) and section['id'] not in ids, label
            ids.add(section['id'])
            translation(section['title'], label + '/title')
            translation(section['lead'], label + '/lead')
            assert section['blocks'], label + ': no blocks'
            for block in section['blocks']:
                kind = block['type']
                if kind == 'text': translation(block['text'], label)
                elif kind == 'list':
                    assert block['items'], label + ': empty list'
                    for item in block['items']: translation(item, label)
                elif kind == 'note':
                    translation(block['title'], label)
                    translation(block['text'], label)
                elif kind == 'code':
                    assert isinstance(block['code'], str) and block['code'].strip(), label
                    assert block['language'] in ['java', 'kotlin', 'bash', 'shell', 'sql', 'text', 'xml', 'json'], label
                    translation(block['caption'], label)
                else: raise ValueError(f'{label}: unsupported block {kind}')
        guide['downloads'] = [
            {'name': p.name, 'path': p.relative_to(ROOT).as_posix()}
            for p in sorted((ROOT / 'examples' / library_id).glob('*'))
            if p.is_file() and p.suffix in ['.java', '.xml', '.md', '.sh', '.sql']
        ]
        assert any(f['name'] == 'Example.java' for f in guide['downloads']), f'{library_id}: missing Example.java'
        guides.append(guide)
    bundle = '/* Generated by scripts/build.py. Edit content/*.json instead. */\nwindow.LIBRARY_GUIDES = ' + json.dumps(guides, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'assets' / 'content.js').write_text(bundle)
    sections = sum(len(g['sections']) for g in guides)
    examples = sum(b['type'] == 'code' for g in guides for s in g['sections'] for b in s['blocks'])
    print(f'Validated {len(guides)} guides, {sections} bilingual sections, {examples} code blocks.')

if __name__ == '__main__':
    main()
